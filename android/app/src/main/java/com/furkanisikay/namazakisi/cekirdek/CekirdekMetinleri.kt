package com.furkanisikay.namazakisi.cekirdek

/**
 * Saf karar sınıflarının (`cekirdek/`) metin tablosu — dil başına BİR blok. SAF.
 *
 * Yer tutucular `{ad}`, `{saat}`, `{giris}`, `{dk}`, `{ipucu}` — [MetinDili.bicim] doldurur.
 * Türkçe metinler fikstür testleriyle BAYT BAYT kilitlidir; İngilizce karşılıklar JS
 * sözlüğünden (`src/core/dil/sozluk/en`) ve `docs/ajan/coklu-dil.md` terim sözlüğünden.
 *
 * Düzen (çeviri ajanları için): her dil kendi bloğunda, sıra tr, en, id, de, fr, bs, ru, ms, ar, ur, es, nl, sq, hi, bn.
 * Çevrilmemiş dilin bloğu İngilizcenin birebir kopyasıdır ve `// ÇEVİRİ: <kod>` satırıyla
 * başlar. Her blok AYNI alanları ve her alan Türkçeyle AYNI yer tutucuları taşır
 * (nöbetçi `CekirdekMetinleriTest`). Yeni dil = yeni blok + [MetinDili.DESTEKLENENLER] +
 * [MetinDili.metinler] eşlemesi + `res/values-xx`.
 */
data class CekirdekMetinleri(
    val dil: String,

    // --- Vakit adları (widget kodu → görünen ad; `VakitKodlari.gorunenAd`) ---
