package com.furkanisikay.namazakisi.cekirdek

/**
 * Saf karar sınıflarının (`cekirdek/`) metin tablosu — dil başına BİR blok. SAF.
 *
 * Yer tutucular `{ad}`, `{saat}`, `{giris}`, `{dk}`, `{ipucu}` — [MetinDili.bicim] doldurur.
 * Türkçe metinler fikstür testleriyle BAYT BAYT kilitlidir; İngilizce karşılıklar JS
 * sözlüğünden (`src/core/dil/sozluk/en`) ve `docs/ajan/coklu-dil.md` terim sözlüğünden.
 *
 * Düzen (çeviri ajanları için): her dil kendi bloğunda, sıra tr, en, id, de, fr, bs, ru, ms.
 * Çevrilmemiş dilin bloğu İngilizcenin birebir kopyasıdır ve `// ÇEVİRİ: <kod>` satırıyla
 * başlar. Her blok AYNI alanları ve her alan Türkçeyle AYNI yer tutucuları taşır
 * (nöbetçi `CekirdekMetinleriTest`). Yeni dil = yeni blok + [MetinDili.DESTEKLENENLER] +
 * [MetinDili.metinler] eşlemesi + `res/values-xx`.
 */
data class CekirdekMetinleri(
    val dil: String,

    // --- Vakit adları (widget kodu → görünen ad; `VakitKodlari.gorunenAd`) ---
    val sabah: String,
    val gunes: String,
    val ogle: String,
    val ikindi: String,
    val aksam: String,
    val yatsi: String,
    /** Klasik geniş widget'ın sabah satırı (JS `vakit.imsakVakti`). */
    val imsakSatiri: String,
    /**
     * Klasik widget "sıradaki vakte" etiketi. Türkçede KULLANILMAZ (sabit yönelme haritası,
     * ek üretilmez); yalnız vakit adları kullanıcıdan geldiğinde çekimsiz kalıp olarak.
     */
    val yonelme: String,
    /** Kayıt kodu tanınmayan "Kıldım" onayında ad. */
    val namaz: String,

    // --- Samimiyet ve "Kıldım" onay bildirimi (KildimOnayMetni) ---
    val kabulDuasi: String,
    val onayGovde: String,

    // --- Widget kutusu (KutuGorunumKarari) ---
    val kutuKilindi: String,
    val kutuKilindiErisim: String,
    val kutuIsaretleniyor: String,
    val kutuIsaretleniyorErisim: String,
    val kutuCikis: String,
    val kutuKilinmadiErisim: String,
    val namazVakti: String,
    val uygulamayiAcin: String,
    val vakitBilgisiYok: String,
    val kutuGiris: String,
    val kutuVakitYokErisim: String,

    // --- Kilit ekranı / kapak ekranı (KilitEkraniKarari) ---
    val kapakIpucu: String,
    val kilitKilinmadiKapak: String,
    val kilitKilinmadi: String,
    val kilitIsaretleyin: String,
    val kilitKilindi: String,

    // --- Asistan (AsistanKarari) ---
    val konumYok: String,
    val veriEski: String,
    val girisBugun: String,
    val girisYarin: String,
    val suAnVakti: String,
    val suAnVaktiCikis: String,
    val siradakiNamaz: String,
    val isaretlendi: String,
    val zatenKilindi: String,
    val vakitYokSiradaki: String,
    val vakitYok: String,
    val onay: String,
    val vakitDegisti: String,

    // --- Araç (AracKarari) ---
    val aracKonumYok: String,
    val aracCamiYok: String,
    val aracKalan: String,
    val aracSiradaki: String,

    // --- Otomasyon (OtomasyonKurallari) ---
    val otoKildim: String,
    val otoGirdiAdli: String,
    val otoGirdi: String,
    val otoIcindeAdli: String,
    val otoIcinde: String,
    val otoCikiyorAdli: String,
    val otoCikiyor: String,
    val otoCamideOlay: String,
    val otoCamide: String,
    val degVakit: String,
    val degVakitKodu: String,
    val degTarih: String,
    val degKalanDk: String,
    val degCami: String,
)

